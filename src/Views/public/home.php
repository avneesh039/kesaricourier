<script>
document.addEventListener('DOMContentLoaded', function() {
    const menuBtn = document.getElementById('kesariMobileMenuBtn');
    const closeBtn = document.getElementById('kesariMobileCloseBtn');
    const navLinks = document.getElementById('kesariNavMenu');
    const overlay = document.getElementById('kesariNavOverlay');

    function openMobileMenu() {
        if (navLinks) navLinks.classList.add('mobile-open');
        if (overlay) overlay.classList.add('active');
        document.body.style.overflow = 'hidden';
    }

    function closeMobileMenu() {
        if (navLinks) navLinks.classList.remove('mobile-open');
        if (overlay) overlay.classList.remove('active');
        document.body.style.overflow = '';
    }

    if (menuBtn) menuBtn.addEventListener('click', openMobileMenu);
    if (closeBtn) closeBtn.addEventListener('click', closeMobileMenu);
    if (overlay) overlay.addEventListener('click', closeMobileMenu);

    // Accordion toggle on mobile
    const dropItems = document.querySelectorAll('.header-nav-list li.has-drop > a');
    dropItems.forEach(item => {
        item.addEventListener('click', function(e) {
            if (window.innerWidth < 992) {
                e.preventDefault();
                const parent = this.parentElement;
                parent.classList.toggle('open');
            }
        });
    });

    // Close menu on clicking nav link
    const allLinks = document.querySelectorAll('.header-nav-list li:not(.has-drop) > a');
    allLinks.forEach(link => {
        link.addEventListener('click', function() {
            if (window.innerWidth < 992) {
                closeMobileMenu();
            }
        });
    });
});
</script>

