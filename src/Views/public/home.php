document.getElementById("contactForm").addEventListener("submit", function(e) {
    e.preventDefault();

    let form = this;
    let isValid = true;
    let submitBtn = document.getElementById("submitBtn");
    let btnText = submitBtn.querySelector(".btn-text");
    let arrowImg = submitBtn.querySelector(".btn-arrow");
    let spinner = submitBtn.querySelector(".spinner-border");

    form.querySelectorAll(".form-control").forEach(input => {
        input.classList.remove("is-invalid");
    });

    let name = form.name.value.trim();
    let email = form.email.value.trim();
    let number = form.number.value.trim();
    let msg = form.msg.value.trim();

    if (name === "") {
        form.name.classList.add("is-invalid");
        isValid = false;
    }

    let emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    if (!emailPattern.test(email)) {
        form.email.classList.add("is-invalid");
        isValid = false;
    }

    let numberPattern = /^[0-9]{10}$/;
    if (!numberPattern.test(number)) {
        form.number.classList.add("is-invalid");
        isValid = false;
    }

    if (msg === "") {
        form.msg.classList.add("is-invalid");
        isValid = false;
    }

    if (!isValid) return;

    submitBtn.disabled = true;
    btnText.textContent = "Sending...";
    arrowImg.style.display = "none";
    spinner.classList.remove("d-none");

    let formData = new FormData(form);

    fetch("/contact-submit", {
        method: "POST",
        body: formData,
        headers: {
            "X-Requested-With": "XMLHttpRequest",
            "X-CSRF-TOKEN": "T3e9OcIm9Z2qoRKMhq2tGieq4xeeYXP0BdVa9WGY"
        }
    })
    .then(res => res.json())
    .then(data => {
        if (data.status === "success") {
            toastr.success(data.message);
            setTimeout(() => {
                window.location.href = data.redirect_url;
            }, 1500);
        } else {
            toastr.error("Something went wrong. Try again!");
        }
    })
    .catch(() => {
        toastr.error("Error while sending form. Please try again!");
    })
    .finally(() => {
        submitBtn.disabled = false;
        btnText.textContent = "Submit";
        arrowImg.style.display = "";
        spinner.classList.add("d-none");
    });
});
