<script>
function showTrackingModal(shipment) {
    document.getElementById('modalConsignmentNo').innerText = 'AWB / Consignment No: ' + shipment.consignment_no;
    document.getElementById('modalStatus').innerText = shipment.status_label;
    document.getElementById('modalOrigin').innerText = shipment.origin;
    document.getElementById('modalDestination').innerText = shipment.destination;
    document.getElementById('modalMode').innerText = shipment.mode;

    const container = document.getElementById('modalMilestones');
    container.innerHTML = '';

    if (shipment.milestones && shipment.milestones.length > 0) {
        shipment.milestones.forEach((m) => {
            const dotColor = m.completed ? '#22c55e' : (m.current ? '#2b3990' : '#dee2e6');
            const item = document.createElement('div');
            item.style.position = 'relative';
            item.style.marginBottom = '20px';
            item.innerHTML = `
                <div style="position:absolute; left:-31px; top:3px; width:14px; height:14px; border-radius:50%; background:${dotColor}; border:2px solid #fff; box-shadow:0 0 0 2px ${dotColor};"></div>
                <div style="font-weight:700; font-size:14px; color:#212529;">${m.title}</div>
                <div style="font-size:12px; color:#6c757d;">${m.description}</div>
                <div style="font-size:11px; color:#adb5bd; margin-top:2px;">${m.date}</div>
            `;
            container.appendChild(item);
        });
    }

    const modal = new bootstrap.Modal(document.getElementById('kesariTrackingModal'));
    modal.show();
}
</script>

